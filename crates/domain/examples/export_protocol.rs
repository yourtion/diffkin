use diffkin_domain::*;
use std::{fs, path::Path};
use ts_rs::{Config, TS};

fn main() -> std::io::Result<()> {
    let config = Config::default();
    let declarations = [
        CompareRequest::decl(&config),
        LineKind::decl(&config),
        DiffLine::decl(&config),
        Comparison::decl(&config),
        CompareError::decl(&config),
        CompareMode::decl(&config),
        ComparisonSpec::decl(&config),
        FileStatus::decl(&config),
        FileSummary::decl(&config),
        ComparisonManifest::decl(&config),
        FrozenFile::decl(&config),
        RepositoryError::decl(&config),
        SourceRange::decl(&config),
        ChangeEvent::decl(&config),
        Presentation::decl(&config),
        CoverageEntry::decl(&config),
        AnalysisResult::decl(&config),
        FileAnalysis::decl(&config),
    ];
    let mut output = String::from("// Generated by pnpm protocol:generate. Do not edit.\n\n");
    for declaration in declarations {
        output.push_str("export ");
        output.push_str(&declaration);
        output.push('\n');
    }
    let destination =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/protocol/src/generated.ts");
    fs::create_dir_all(destination.parent().expect("protocol directory"))?;
    let output = output
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    fs::write(destination, output)
}
